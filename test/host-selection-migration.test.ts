import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Store, operationInputHash } from '../core/store/store';
import { QueueRuntime } from '../service/runtime-owner';
import { submissionSchema } from '../shared/contracts';
import type { Adapter } from '../core/host/adapter';

test('the schema step marks host selection migration complete without rewriting stored identity', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'selection-migration-'));
  const path = join(dir, 'queue.sqlite');
  let store = new Store(path);
  store.setMeta('hostId', 'a');
  const make = (id: string, host: string) => store.insert(submissionSchema.parse({ submissionId: id, title: id, repoPath: '/repo', planningCommit: 'a'.repeat(40), handoffPath: 'h', originAgentId: 'origin' }), host, 'h', 'a'.repeat(40));
  const old = make('old', 'a'), unknown = make('unknown', ''), other = make('other', 'b');
  store.db.prepare("UPDATE tasks SET data=json_remove(data,'$.hostSelection') WHERE id IN (?,?,?)").run(old.id, unknown.id, other.id);
  const payload = { type: 'review_entry', input: {} };
  const accepted = store.acceptOperation({ key: 'legacy-intent', kind: 'review_entry', inputHash: operationInputHash(payload), payload });
  if (!('accepted' in accepted)) throw Error('backpressured');
  const events = store.eventsAll(old.id), intentId = accepted.operation.id;
  store.setMeta('legacyHostSelectionOperations', ['impossible']);
  store.setMeta('schema', 50);
  store.close();
  store = new Store(path);
  assert.equal(store.task(old.id).hostSelection, undefined);
  assert.equal(store.task(unknown.id).hostSelection, undefined);
  assert.equal(store.task(other.id).hostSelection, undefined);
  assert.equal(store.operation(intentId)?.hostSelection, undefined);
  assert.equal(store.getMeta('legacyHostSelectionOperations'), undefined);
  assert.equal(store.getMeta('hostSelectionMigrationV1'), true);
  assert.deepEqual(store.eventsAll(old.id), events);
  store.close();
  const client = { isConnected: false };
  const adapter = { client, hostId: 'a', socketPath: join(dir, 'callback.sock'), helperPath: join(dir, 'helper.mjs'), connect: async () => { client.isConnected = true; }, close: async () => { client.isConnected = false; }, catalog: async () => ({ providers: [] }) } as unknown as Adapter;
  const open = () => new QueueRuntime({ dataDir: dir, adapterFactory: () => adapter, timers: false });
  let runtime = open();
  await runtime.started; await runtime.bootstrap;
  assert.equal(runtime.store.task(old.id).hostSelection, undefined);
  assert.equal(runtime.store.task(unknown.id).hostSelection, undefined);
  assert.equal(runtime.store.task(other.id).hostSelection, undefined);
  assert.equal(runtime.store.getMeta('legacyHostSelectionOperations'), undefined);
  assert.equal(runtime.store.getMeta('hostSelectionMigrationV1'), true);
  assert.deepEqual(runtime.store.eventsAll(old.id), events);
  await runtime.drain();
  runtime = open(); await runtime.started; await runtime.bootstrap;
  assert.deepEqual(runtime.store.operationPayload(intentId), payload);
  assert.equal(runtime.store.task(other.id).hostSelection, undefined);
  assert.equal(runtime.store.getMeta('legacyHostSelectionOperations'), undefined);
  assert.equal(runtime.store.getMeta('hostSelectionMigrationV1'), true);
  await runtime.drain();
});
