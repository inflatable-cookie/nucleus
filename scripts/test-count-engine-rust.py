"""Check the line counter against synthetic committed source."""

from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


COUNTER = Path(__file__).with_name("count-engine-rust.py").resolve()


class RustLineCountTest(unittest.TestCase):
    def test_counts_commits_with_their_own_source_inventory(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = Path(tmp)

            def git(*args):
                return subprocess.check_output(["git", *args], cwd=repo, text=True).strip()

            def write(path, contents):
                file = repo / path
                file.parent.mkdir(parents=True, exist_ok=True)
                file.write_text(contents)

            def commit(message):
                git("add", ".")
                git("-c", "user.name=Metric Test", "-c", "user.email=metric@example.invalid",
                    "commit", "-qm", message)
                return git("rev-parse", "HEAD")

            git("init", "-q")
            root = "engine/crates/example"
            write(f"{root}/src/lib.rs", """\
/* Nested /* comment */ continues
   here. */
#[cfg(not(test))]
pub fn shipped<'a>(text: &'a str) -> &'a str { text } // trailing comment

const RAW: &str = r###"
// part of the string
/* also part of the string */

"###;
const COOKED: &str = "
// part of the cooked string
";
const QUOTE: char = '\\'';

/// This document belongs to the excluded item.
#[allow(dead_code)]
#[cfg(any(test, /* gate */ feature = r"loopback-fixture",))]
#[doc = "fixture only"]
fn excluded() {}
#[cfg(feature = "loopback-fixture")] fn fixture() {}
#[cfg_attr(not(test), cfg(all(test, unix)))]
fn excluded_via_cfg_attr() {}
#[cfg(any(test, target_os = "macos"))]
fn on_a_production_platform() {}
#[cfg(test)]
mod fixtures;
#[cfg(test)]
#[path = "alternate.rs"]
mod fixture_by_path;
#[cfg(any(test, feature = "loopback-fixture"))]
mod helper;
#[test]
fn test_function() {}
mod internal {
    #![cfg(test)]
    fn test_helper() {}
}
enum Choice {
    #[cfg(test)] Test
    ,
    Real,
}
""")
            write(f"{root}/src/fixtures.rs", "fn fixture_helper() {}\n")
            write(f"{root}/src/alternate.rs", "fn fixture_helper() {}\n")
            write(f"{root}/src/helper/mod.rs", "mod child;\n")
            write(f"{root}/src/helper/child.rs", "fn fixture_helper() {}\n")
            write(f"{root}/src/sample_tests.rs", "fn test_helper() {}\n")
            write(f"{root}/src/generated/wire.rs", "fn generated() {}\n")
            write(f"{root}/src/bindings.rs", "// @generated by an example generator\nfn generated() {}\n")
            write(f"{root}/tests/integration.rs", "fn integration_test() {}\n")
            write("other/src/main.rs", "fn ignored() {}\n")
            base = commit("Base")
            write(f"{root}/src/next.rs", "fn next() {}\n")
            head = commit("Add a production file")
            write(f"{root}/src/uncommitted.rs", "fn untracked() {}\n")

            result = subprocess.check_output(
                [sys.executable, str(COUNTER), base, head], cwd=repo, text=True
            ).splitlines()
            self.assertEqual(result, [
                f"{base} {base[:12]}  15",
                f"{head} {head[:12]}  16  (+1 vs {base})",
            ])


if __name__ == "__main__":
    unittest.main()
